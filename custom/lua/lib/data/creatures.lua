function M.byteswap16(v) return ((v & 0xFF) << 8) | ((v >> 8) & 0xFF) end

-- reverse index: byte-swapped hex -> id
local _by_hex = {}
for id in pairs(C) do _by_hex[M.byteswap16(id)] = id end

function M.by_hex(hex)
  local id = _by_hex[hex]
  return id and C[id] or nil
end

function M.get(id) return C[id] end

