function M.survival_bonus_pct(v)
  for _, row in ipairs(M.SurvivalBonus) do
    if v >= row.min and v <= row.max then return row.p end
  end
  return 0
end

-- XP needed to reach a given level (1-based; clamps to table bounds).
function M.xp_for_level(level)
  if level < 1 then level = 1 end
  if level > #M.ExpTable then level = #M.ExpTable end
  return M.ExpTable[level]
end

